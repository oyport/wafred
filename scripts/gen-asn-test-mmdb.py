#!/usr/bin/env python3
"""Generate the synthetic MaxMind DB fixture used by the ASN tests.

`pingwaf-server/src/asn.rs` decodes ASN records out of a MaxMind DB
(`.mmdb`). The crate's published package ships no test database and MaxMind's
own test data is licensed separately, so the tests use this file instead: a
hand-built, ~200-byte database generated by the code below. It contains no
MaxMind data at all — one synthetic AS number for `0.0.0.0/1`, nothing for
`128.0.0.0/1`.

Format reference: https://maxmind.github.io/MaxMind-DB/

Layout written here (record size 24, one search-tree node, IPv4):

    [ 24 nodes ][ 16-byte separator ][ data section ][ marker ][ metadata ]

    The search tree is a linear chain of 24 nodes following the bits of
    `8.8.8.0/24`; the record on the path points at the next node and the last
    one at the data section, while every off-path record holds `node_count`
    (the format's "no data" value).

Regenerate with:

    python3 scripts/gen-asn-test-mmdb.py wafred-server/assets/test/asn-test.mmdb

The output is deterministic, so re-running it on an unchanged script produces
an identical file.
"""

from __future__ import annotations

import struct
import sys

# MaxMind DB type ids (https://maxmind.github.io/MaxMind-DB/#data-types).
TYPE_STRING = 2
TYPE_UINT16 = 5
TYPE_UINT32 = 6
TYPE_MAP = 7
TYPE_UINT64 = 9
TYPE_ARRAY = 11

METADATA_MARKER = b"\xab\xcd\xef" + b"MaxMind.com"

# The single record the fixture resolves to.
FIXTURE_ASN = 64500
FIXTURE_ORG = "Example Hosting, Ltd. (synthetic test data)"
# Prefix the record covers, as (network, prefix length).
FIXTURE_NETWORK = "8.8.8.0"
FIXTURE_PREFIX_LEN = 24


def _size_prefix(type_id: int, size: int) -> bytes:
    """Control byte(s) for a value of `type_id` holding `size` elements."""
    if type_id <= 7:
        head = type_id << 5
        extended = b""
    else:
        head = 0
        extended = bytes([type_id - 7])
    if size < 29:
        return bytes([head | size]) + extended
    if size < 29 + 256:
        return bytes([head | 29]) + extended + bytes([size - 29])
    raise ValueError("fixture values stay below the 285-byte size step")


def uint16(value: int) -> bytes:
    return _size_prefix(TYPE_UINT16, 2) + struct.pack(">H", value)


def uint32(value: int) -> bytes:
    return _size_prefix(TYPE_UINT32, 4) + struct.pack(">I", value)


def uint64(value: int) -> bytes:
    return _size_prefix(TYPE_UINT64, 8) + struct.pack(">Q", value)


def utf8(value: str) -> bytes:
    encoded = value.encode("utf-8")
    return _size_prefix(TYPE_STRING, len(encoded)) + encoded


def map_of(entries: list[tuple[bytes, bytes]]) -> bytes:
    out = _size_prefix(TYPE_MAP, len(entries))
    for key, value in entries:
        out += key + value
    return out


def array_of(items: list[bytes]) -> bytes:
    return _size_prefix(TYPE_ARRAY, len(items)) + b"".join(items)


def _prefix_bits(network: str, prefix_len: int) -> list[int]:
    """The leading `prefix_len` bits of an IPv4 network address."""
    octets = [int(part) for part in network.split(".")]
    value = 0
    for octet in octets:
        value = (value << 8) | octet
    return [(value >> (31 - index)) & 1 for index in range(prefix_len)]


def build() -> bytes:
    # Data section: one ASN record.
    record = map_of(
        [
            (utf8("autonomous_system_number"), uint32(FIXTURE_ASN)),
            (utf8("autonomous_system_organization"), utf8(FIXTURE_ORG)),
        ]
    )

    bits = _prefix_bits(FIXTURE_NETWORK, FIXTURE_PREFIX_LEN)
    node_count = len(bits)
    data_pointer = node_count + 16  # offset 0 of the data section
    tree = b""
    for depth, bit in enumerate(bits):
        on_path = data_pointer if depth + 1 == node_count else depth + 1
        # Off-path records hold node_count, which the reader maps to "no data".
        left, right = (on_path, node_count) if bit == 0 else (node_count, on_path)
        tree += struct.pack(">I", left)[1:] + struct.pack(">I", right)[1:]

    metadata = map_of(
        [
            (utf8("binary_format_major_version"), uint16(2)),
            (utf8("binary_format_minor_version"), uint16(0)),
            (utf8("build_epoch"), uint64(1_700_000_000)),
            (utf8("database_type"), utf8("GeoLite2-ASN")),
            (
                utf8("description"),
                map_of(
                    [
                        (utf8("en"), utf8("synthetic ASN fixture for tests")),
                    ]
                ),
            ),
            (utf8("ip_version"), uint16(4)),
            (utf8("languages"), array_of([utf8("en")])),
            (utf8("node_count"), uint32(node_count)),
            (utf8("record_size"), uint16(24)),
        ]
    )

    return tree + b"\x00" * 16 + record + METADATA_MARKER + metadata


def main() -> int:
    if len(sys.argv) != 2:
        print(f"usage: {sys.argv[0]} <output.mmdb>", file=sys.stderr)
        return 2
    data = build()
    with open(sys.argv[1], "wb") as handle:
        handle.write(data)
    print(f"wrote {sys.argv[1]} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())